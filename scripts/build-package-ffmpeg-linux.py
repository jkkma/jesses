    def run(self, args, cwd=None, timeout=1800, input_text=None, capture=False):
        args = [str(arg) for arg in args]
        cwd = cwd or self.directory
        self.commands.append({"argv": args, "cwd": str(cwd), "stdin": input_text})
        log_path = self.directory / "build.log"
        try:
            with log_path.open("a", encoding="utf-8") as log:
                log.write(json.dumps(self.commands[-1]) + "\n")
                log.flush()
                result = subprocess.run(args, cwd=cwd, env=self.env, input=input_text, text=True, stdout=subprocess.PIPE if capture else log, stderr=subprocess.STDOUT, timeout=timeout, check=True)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
            lines = log_path.read_text(encoding="utf-8", errors="replace").splitlines()
            tail = lines[-100:]
            print(f"Build command failed: {json.dumps(args)}", file=sys.stderr)
            print(f"Last {len(tail)} lines of {log_path}:", file=sys.stderr)
            print("\n".join(tail), file=sys.stderr)
            captured = getattr(error, "stdout", None)
            if captured:
                if isinstance(captured, bytes):
                    captured = captured.decode(errors="replace")
                captured_tail = captured.splitlines()[-100:]
                print(f"Last {len(captured_tail)} captured output lines:", file=sys.stderr)
                print("\n".join(captured_tail), file=sys.stderr)
            raise
        return result.stdout if capture else None

    def source(self, item: dict) -> Path:
        archive = download(item, self.cache)
        packaged = self.delivery / "sources" / item["filename"]
        shutil.copy2(archive, packaged)
        self.sources.append(record(packaged, self.delivery, url=item["url"]))
        if "bundleRoot" not in item:
            source = extract(archive, self.work / "ffmpeg", item["sourceRoot"])
        else:
            bundle = extract(archive, self.work / (item["id"] + "-bundle"), item["bundleRoot"])
            container = bundle.parent
            if "embeddedArchive" in item:
                embedded = container / relative(item["embeddedArchive"])
                if digest(embedded) != item["embeddedSha256"]:
                    raise ValueError("An embedded upstream source checksum differs.")
                source = extract(embedded, self.work / item["id"], item["sourceRoot"])
            else:
                bare = container / relative(item["gitDirectory"])
                source = self.work / item["id"]
                self.run(["git", "clone", "--no-checkout", "--no-hardlinks", "--local", bare, source], timeout=120)
                self.run(["git", "-C", source, "checkout", "--detach", item["gitCommit"]], timeout=120)
                if self.run(["git", "-C", source, "rev-parse", "HEAD"], capture=True).strip() != item["gitCommit"]:
                    raise ValueError("The extracted local Git source has a different revision.")
            for patch in item.get("patches", []):
                path = container / relative(patch["path"])
                if digest(path) != patch["sha256"]:
                    raise ValueError("The source patch checksum differs.")
                self.patches.setdefault(item["id"], []).append(path)
        identifier = item.get("id", "ffmpeg")
        licenses = self.delivery / "licenses" / identifier
        licenses.mkdir()
        for name in item["licenseFiles"]:
            original = source / relative(name)
            target = licenses / name.replace("/", "-")
            if not original.is_file() or original.stat().st_size > 1024 * 1024:
                raise ValueError(f"Missing or oversized license: {identifier}/{name}")
            shutil.copy2(original, target)
            self.licenses.append(record(target, self.delivery))
        print(f"Verified source and licenses: {identifier}", flush=True)
        return source

    def make(self, source, *targets):
        self.run(["make", f"-j{self.jobs}", *targets], cwd=source)

    def autotools(self, source, *options):
        self.run([source / "configure", f"--prefix={self.prefix}", "--libdir=" + str(self.prefix / "lib"), "--disable-shared", "--enable-static", *options], cwd=source, timeout=300)
        self.make(source)
        self.make(source, "install")

