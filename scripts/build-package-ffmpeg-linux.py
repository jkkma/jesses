def digest(path: Path) -> str:
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def relative(value: str) -> PurePosixPath:
    if not value or "\\" in value or ":" in value or "\0" in value:
        raise ValueError(f"Invalid source path: {value!r}")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or not path.parts:
        raise ValueError(f"Invalid source path: {value!r}")
    return path


def download(record: dict, cache: Path) -> Path:
    filename = relative(record["filename"])
    if len(filename.parts) != 1 or not re.fullmatch(r"[a-f0-9]{64}", record["sha256"]):
        raise ValueError("Invalid locked source filename or checksum.")
    destination = cache / filename
    if destination.exists():
        if destination.is_symlink() or not destination.is_file() or digest(destination) != record["sha256"]:
            raise ValueError(f"The cached source checksum differs: {destination}")
        return destination
    if not record["url"].startswith("https://"):
        raise ValueError("Source downloads require HTTPS.")
    temporary = cache / (str(filename) + ".partial-" + uuid.uuid4().hex)
    with urlopen(Request(record["url"], headers={"User-Agent": "jesses-linux-package"}), timeout=90) as response, temporary.open("xb") as output:
        size = 0
        while block := response.read(1024 * 1024):
            size += len(block)
            if size > MAX_ARCHIVE:
                raise ValueError("The source download exceeds its size limit.")
            output.write(block)
    if digest(temporary) != record["sha256"]:
        raise ValueError(f"Source checksum mismatch; retained for inspection: {temporary}")
    # A concurrent downloader cannot replace an existing cached archive.
    os.link(temporary, destination)
    temporary.unlink()
    return destination


def extract(archive: Path, destination: Path, root: str) -> Path:
    """Extract bounded data only; materialize safe internal links as file copies."""
    relative(root)
    destination.mkdir(parents=True, exist_ok=False)
    with tarfile.open(archive) as bundle:
        members = bundle.getmembers()
        if len(members) > 200_000 or sum(item.size for item in members) > 2 * 1024**3:
            raise ValueError("The source archive exceeds extraction bounds.")
        files = {}
        links = []
        directories = []
        for member in members:
            path = relative(member.name)
            if path.parts[0] != root or not (member.isdir() or member.isfile() or member.issym() or member.islnk()):
                raise ValueError(f"Unexpected source archive member: {member.name}")
            if member.isdir():
                directories.append((path, member.mtime))
                continue
            if path.as_posix() in files:
                raise ValueError("The source archive repeats a file path.")
            files[path.as_posix()] = member
            if member.issym() or member.islnk():
                linked = posixpath.normpath(posixpath.join(path.parent.as_posix(), member.linkname)) if member.issym() else member.linkname
                target = relative(linked)
                if target.parts[0] != root:
                    raise ValueError("A source archive link escapes its root.")
                links.append((path, target, member.mtime))
        for path, _ in directories:
            (destination / path).mkdir(parents=True, exist_ok=True)
        for name, member in files.items():
            if not member.isfile():
                continue
            target = destination / relative(name)
            target.parent.mkdir(parents=True, exist_ok=True)
            with bundle.extractfile(member) as source, target.open("xb") as output:
                shutil.copyfileobj(source, output)
            target.chmod(0o755 if member.mode & 0o111 else 0o644)
            os.utime(target, (member.mtime, member.mtime))
        for path, linked, mtime in links:
            source = files.get(linked.as_posix())
            if source is None or not source.isfile():
                raise ValueError("A source archive link must identify a regular member.")
            target = destination / path
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(destination / linked, target)
            os.utime(target, (mtime, mtime))
        for path, mtime in directories:
            os.utime(destination / path, (mtime, mtime))
    result = destination / root
    if not result.is_dir():
        raise ValueError("The expected source directory is absent.")
    return result


def record(path: Path, delivery: Path, **extra) -> dict:
    return {**extra, "path": path.relative_to(delivery).as_posix(), "sha256": digest(path)}


