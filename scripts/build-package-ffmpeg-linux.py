        print(f"Building static library: {identifier}", flush=True)
        for patch in self.patches.get(identifier, []):
            self.run(["patch", "-p1", "--batch", "--forward", "-i", patch], cwd=source, timeout=30)
        if identifier == "bzip2":
            self.make(source, "libbz2.a", f"CFLAGS={self.env['CFLAGS']}")
            (self.prefix / "include").mkdir(exist_ok=True)
            (self.prefix / "lib").mkdir(exist_ok=True)
            shutil.copy2(source / "bzlib.h", self.prefix / "include/bzlib.h")
            shutil.copy2(source / "libbz2.a", self.prefix / "lib/libbz2.a")
        elif identifier == "zlib":
            self.run([source / "configure", f"--prefix={self.prefix}", "--static"], cwd=source, timeout=300)
            self.make(source)
            self.make(source, "install")
        elif identifier == "xz":
            self.autotools(source, "--disable-doc", "--disable-nls", "--disable-xz", "--disable-xzdec", "--disable-lzmadec", "--disable-lzmainfo", "--disable-scripts")
        elif identifier == "lame":
            self.autotools(source, "--disable-frontend", "--disable-decoder", "--without-libiconv")
        elif identifier in {"libogg", "libvorbis"}:
            self.autotools(source, "--disable-docs")
        elif identifier == "opus":
            self.autotools(source, "--disable-doc", "--disable-extra-programs")
        elif identifier == "zimg":
            self.run(["sh", "autogen.sh"], cwd=source, timeout=300)
            self.autotools(source)
        elif identifier == "x264":
            self.run([source / "configure", f"--prefix={self.prefix}", "--enable-static", "--enable-pic", "--disable-cli", "--disable-opencl"], cwd=source, timeout=300)
            self.make(source)
            self.make(source, "install")
        elif identifier == "libvpx":
            self.run([source / "configure", f"--prefix={self.prefix}", "--target=x86_64-linux-gcc", "--enable-static", "--disable-shared", "--enable-pic", "--enable-vp9-highbitdepth", "--disable-examples", "--disable-tools", "--disable-unit-tests", "--disable-docs"], cwd=source, timeout=300)
            self.make(source)
            self.make(source, "install")
        elif identifier == "dav1d":
            self.meson_build(identifier, source, "-Denable_tools=false", "-Denable_tests=false")
        elif identifier == "expat":
            build = self.work / "expat-build"
            self.run(["cmake", "-S", source, "-B", build, "-G", "Ninja", f"-DCMAKE_INSTALL_PREFIX={self.prefix}", "-DCMAKE_INSTALL_LIBDIR=lib", "-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_POSITION_INDEPENDENT_CODE=ON", "-DEXPAT_SHARED_LIBS=OFF", "-DEXPAT_BUILD_TOOLS=OFF", "-DEXPAT_BUILD_EXAMPLES=OFF", "-DEXPAT_BUILD_TESTS=OFF", "-DEXPAT_BUILD_DOCS=OFF", "-DEXPAT_BUILD_FUZZERS=OFF"], timeout=300)
            self.run(["cmake", "--build", build, "--parallel", self.jobs])
            self.run(["cmake", "--install", build])
        elif identifier == "freetype":
            self.meson_build(identifier, source, "-Dzlib=system", "-Dbzip2=enabled", "-Dbrotli=enabled", "-Dpng=enabled", "-Dharfbuzz=disabled", "-Dtests=disabled")
        elif identifier in {"brotli", "libpng"}:
            build = self.work / f"{identifier}-build"
            options = ["-DBUILD_SHARED_LIBS=OFF", "-DBROTLI_DISABLE_TESTS=ON"] if identifier == "brotli" else ["-DPNG_SHARED=OFF", "-DPNG_STATIC=ON", "-DPNG_TESTS=OFF", "-DPNG_TOOLS=OFF", "-DPNG_EXECUTABLES=OFF", f"-DZLIB_LIBRARY={self.prefix}/lib/libz.a", f"-DZLIB_INCLUDE_DIR={self.prefix}/include"]
