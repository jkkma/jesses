//! Container-preserving utility publication; no implicit Matroska substitution.
use super::*;

pub(super) fn format(path: &Path) -> Result<(&'static str, &'static str), AppError> {
    match path
        .extension()
        .and_then(|value| value.to_str())
        .unwrap_or("")
        .to_ascii_lowercase()
        .as_str()
    {
        "mkv" => Ok(("matroska", "mkv")),
        "mp4" => Ok(("mp4", "mp4")),
        "mov" => Ok(("mov", "mov")),
        "webm" => Ok(("webm", "webm")),
        "ts" => Ok(("mpegts", "ts")),
        "m2ts" => Ok(("mpegts", "m2ts")),
        "mts" => Ok(("mpegts", "mts")),
        "avi" => Ok(("avi", "avi")),
        "ivf" => Ok(("ivf", "ivf")),
        _ => Err(error(
            "UTILITY_OUTPUT_FORMAT_UNSUPPORTED",
            "Choose a compatible MKV, MP4, MOV, WebM, MPEG-TS, AVI or IVF output container.",
            Some(path),
        )),
    }
}

pub(super) fn source_extension(input: &str) -> Result<String, AppError> {
    let (_, extension) = format(Path::new(input))?;
    Ok(format!(".{extension}"))
}

pub(super) fn grain_format(path: &Path) -> Result<(&'static str, &'static str), AppError> {
    let value = format(path)?;
    if matches!(value.0, "matroska" | "mp4" | "webm" | "ivf") {
        Ok(value)
    } else {
        Err(error(
            "UTILITY_OUTPUT_FORMAT_UNSUPPORTED",
            "AV1 grain headers require a compatible MKV, MP4, WebM or IVF container; AV1 is not supported by the MOV muxer.",
            Some(path),
        ))
    }
}

pub(super) fn mux_metadata(args: &mut Vec<OsString>, document: &ProbeDocument, format: &str) {
    if matches!(format, "mp4" | "mov") {
        args.extend(["-movflags".into(), "use_metadata_tags+write_colr".into()]);
        // These are real ISO header fields, already emitted by the muxer.
        // Copying their FFprobe dictionary entries into mdta produces duplicate
        // values such as `isom;isom`, rather than preserving the original field.
        for key in ["major_brand", "minor_version", "compatible_brands"] {
            args.extend(["-metadata".into(), format!("{key}=").into()]);
        }
        if let Some((_, brand)) = document
            .format
            .as_ref()
            .and_then(|format| {
                format
                    .tags
                    .iter()
                    .find(|(key, _)| key.eq_ignore_ascii_case("major_brand"))
            })
            .filter(|(_, brand)| {
                brand.len() == 4
                    && brand
                        .bytes()
                        .all(|byte| byte.is_ascii_alphanumeric() || byte == b' ')
            })
        {
            args.extend(["-brand".into(), brand.into()]);
        }
        for (position, stream) in document.streams.iter().enumerate() {
            // ISO BMFF's name atom is read as `name`, but its writer consumes
            // `title`; an explicit round-trip mapping preserves that same atom.
            if let Some((_, title)) = stream
                .tags
                .iter()
                .find(|(key, _)| key.eq_ignore_ascii_case("title"))
                .or_else(|| {
                    stream
                        .tags
                        .iter()
                        .find(|(key, _)| key.eq_ignore_ascii_case("name"))
                })
            {
                args.extend([
                    format!("-metadata:s:{position}").into(),
                    format!("title={title}").into(),
                ]);
            }
        }
    }
    if format == "matroska" {
        args.extend(["-default_mode".into(), "passthrough".into()]);
    }
}

/// grav1synth's writer copies codec parameters/global tags but omits stream
/// metadata, dispositions, chapters and attachments. Take the changed AV1 track
/// from its validated derivative and every other packet/tag from the original.
pub(super) async fn restore_grain_metadata(
    ffmpeg: &Path,
    source: &Source,
    modified: &Temporary,
    document: &ProbeDocument,
    output: &Path,
    cancel: &watch::Receiver<bool>,
) -> Result<Temporary, AppError> {
    let (format, extension) = format(output)?;
    let temporary = Temporary::create_extension(output, &nonce("grain-container"), extension)?;
    let mut args: Vec<OsString> = ["-hide_banner", "-v", "warning", "-nostdin", "-copyts", "-i"]
        .into_iter()
        .map(Into::into)
        .collect();
    args.push(os(&source.path));
    args.extend(["-i".into(), os(&modified.path)]);
    let first_video = document
        .streams
        .iter()
        .find(|stream| stream.codec_type.as_deref() == Some("video"))
        .map(|stream| stream.index);
    let mut position = 0;
    for stream in &document.streams {
        // ISO BMFF chapter text is regenerated by -map_chapters, not duplicated
        // as an unrelated codec-bin-data stream.
        if !document.chapters.is_empty()
            && matches!(format, "mp4" | "mov")
            && stream.codec_type.as_deref() == Some("data")
            && stream.codec_name.as_deref() == Some("bin_data")
            && stream.codec_tag_string.as_deref() == Some("text")
        {
            continue;
        }
        args.extend([
            "-map".into(),
            if Some(stream.index) == first_video {
                "1:v:0".into()
            } else {
                format!("0:{}", stream.index).into()
            },
        ]);
        args.extend([
            format!("-map_metadata:s:{position}").into(),
            format!("0:s:{}", stream.index).into(),
        ]);
        let disposition = stream
            .disposition
            .iter()
            .filter(|(_, value)| **value != 0)
            .map(|(key, _)| key.as_str())
            .collect::<Vec<_>>()
            .join("+");
        args.extend([
            format!("-disposition:{position}").into(),
            if disposition.is_empty() {
                "0".into()
            } else {
                disposition.into()
            },
        ]);
        position += 1;
    }
    args.extend([
        "-c".into(),
        "copy".into(),
        "-copytb".into(),
        "1".into(),
        "-map_metadata".into(),
        "0".into(),
        "-map_chapters".into(),
        "0".into(),
        "-avoid_negative_ts".into(),
        "disabled".into(),
    ]);
    mux_metadata(&mut args, document, format);
    if matches!(format, "mp4" | "mov")
        && let Some(scale) = document
            .streams
            .iter()
            .find(|stream| Some(stream.index) == first_video)
            .and_then(|stream| stream.time_base.as_deref())
            .and_then(|rate| rate.strip_prefix("1/"))
            .and_then(|value| value.parse::<u32>().ok())
            .filter(|value| *value > 0 && *value <= i32::MAX as u32)
    {
        args.extend(["-video_track_timescale".into(), scale.to_string().into()]);
    }
    if format == "ivf" {
        let rate = document
            .streams
            .iter()
            .find(|stream| Some(stream.index) == first_video)
            .and_then(|stream| {
                [
                    stream.avg_frame_rate.as_deref(),
                    stream.r_frame_rate.as_deref(),
                ]
                .into_iter()
                .flatten()
                .find(|rate| {
                    rate.split_once('/').is_some_and(|(num, den)| {
                        num.parse::<u32>().is_ok_and(|num| num > 0)
                            && den.parse::<u32>().is_ok_and(|den| den > 0)
                    })
                })
            })
            .ok_or_else(|| {
                error(
                    "UTILITY_SOURCE_INVALID",
                    "IVF restoration needs its declared positive frame clock.",
                    Some(&source.path),
                )
            })?;
        args.extend(["-r".into(), rate.into()]);
    }
    args.extend(["-y".into(), "-f".into(), format.into(), os(&temporary.path)]);
    checked(
        ffmpeg.to_owned(),
        args,
        cancel,
        MEDIA_LIMIT,
        Some(&source.path),
        "Original container and track-metadata restoration",
    )
    .await?;
    Ok(temporary)
}
