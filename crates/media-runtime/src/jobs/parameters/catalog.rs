fn spec(
    name: &'static str,
    label: &'static str,
    bounds: (i32, i32),
    kind: ValueKind,
    choices: &'static [&'static str],
    group: &'static str,
    help: (&'static str, &'static str),
) -> Spec {
    Spec {
        name,
        label,
        flag: name,
        min: bounds.0,
        max: bounds.1,
        kind,
        choices,
        group,
        description: help.0,
        example: help.1,
    }
}

