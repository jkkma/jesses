fn number(
    name: &'static str,
    label: &'static str,
    min: i32,
    max: i32,
    group: &'static str,
    description: &'static str,
    example: &'static str,
) -> Spec {
    native(spec(
        name,
        label,
        (min, max),
        ValueKind::Whole,
        &[],
        group,
        (description, example),
    ))
}
fn decimal(
    name: &'static str,
    label: &'static str,
    min: i32,
    max: i32,
    group: &'static str,
    description: &'static str,
    example: &'static str,
) -> Spec {
    native(spec(
        name,
        label,
        (min, max),
        ValueKind::Decimal,
        &[],
        group,
        (description, example),
    ))
}
fn choice(
    name: &'static str,
    label: &'static str,
    choices: &'static [&'static str],
    group: &'static str,
    description: &'static str,
    example: &'static str,
) -> Spec {
    native(spec(
        name,
        label,
        (0, 0),
        ValueKind::Choice,
        choices,
        group,
        (description, example),
    ))
}
fn choice_list(
    name: &'static str,
    label: &'static str,
    choices: &'static [&'static str],
    group: &'static str,
    description: &'static str,
    example: &'static str,
) -> Spec {
    native(spec(
        name,
        label,
        (0, 0),
        ValueKind::ChoiceList,
        choices,
        group,
        (description, example),
    ))
}

